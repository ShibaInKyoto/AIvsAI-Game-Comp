constexpr float kFirstLine = 1.2f;
constexpr float kLineInterval = 2.4f;
constexpr float kTypeSpeed = 45.0f; // characters per second
constexpr float kCreditsStart = 15.5f;
constexpr float kScrollSpeed = 85.0f; // UI units per second
constexpr float kSkipDelay = 1.0f;
constexpr float kAutoContinue = 7.0f; // seconds after the roll settles

struct EpilogueLine {
    const char* text;
    bool heading;
};

constexpr std::array<EpilogueLine, 5> kEpilogue{{
    {"THE CORE IS SILENT.", true},
    {"Every sector of the mainframe answers to no one now.", false},
    {"The grid you broke is already reassembling itself,", false},
    {"line by line, into something new. Something free.", false},
    {"PROCESS COMPLETE  //  SYSTEM LIBERATED", true},
}};

enum class CreditKind {
    Title,
    Heading,
    Body,
    Gap
};

struct CreditLine {
    CreditKind kind;
    std::string text;
};

float LineHeight(CreditKind kind) {
    switch (kind) {
    case CreditKind::Title: return 120.0f;
    case CreditKind::Heading: return 48.0f;
    case CreditKind::Body: return 40.0f;
    case CreditKind::Gap: return 70.0f;
    }
    return 40.0f;
}

std::vector<CreditLine> BuildCredits(const RunSummary& run) {
    const ShipInfo& ship = GetShipInfo(run.config.ship);
    const int seconds = static_cast<int>(run.stats.time);
    return {
        {CreditKind::Title, "GRIDBREAKER"},
        {CreditKind::Body, "A neon roguelite built from scratch in one week."},
        {CreditKind::Body, "Every sound, every note and every shape is generated by code."},
        {CreditKind::Gap, ""},
        {CreditKind::Heading, "YOUR RUN"},
        {CreditKind::Body, std::string(ship.name) + "  //  " + DifficultyName(run.config.difficulty) + "  //  " +
                               GameModeName(run.config.mode)},
        {CreditKind::Body, TextFormat("%d:%02d  //  LEVEL %d  //  %s HOSTILES", seconds / 60, seconds % 60, run.level,
                                      FormatThousands(run.stats.kills).c_str())},
        {CreditKind::Body, "SCORE  " + FormatThousands(run.stats.score)},
        {CreditKind::Gap, ""},
        {CreditKind::Heading, "POWERED BY"},
        {CreditKind::Body, "raylib 5.5  -  Ramon Santamaria and contributors"},
        {CreditKind::Body, "doctest  -  Viktor Kirilov"},
        {CreditKind::Gap, ""},
        {CreditKind::Heading, "TYPEFACES"},
        {CreditKind::Body, "Orbitron  -  Matt McInerney"},
        {CreditKind::Body, "Rajdhani  -  Indian Type Foundry"},
        {CreditKind::Body, "SIL Open Font License 1.1"},
        {CreditKind::Gap, ""},
        {CreditKind::Gap, ""},
        {CreditKind::Title, "THANK YOU FOR PLAYING"},
    };
}

