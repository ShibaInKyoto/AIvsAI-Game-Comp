EndingScene::EndingScene(App& app, const RunSummary& summary, int creditsEarned)
    : Scene(app), summary_(summary), creditsEarned_(creditsEarned), backdrop_(palette::kUiGood) {}

void EndingScene::OnEnter() {
    app_.Audio().Music().SetMood(MusicMood::Victory, 0);
    HideCursor();
}

void EndingScene::Finish() {
    if (leaving_) {
        return;
    }
    leaving_ = true;
    ShowCursor();
    app_.ChangeScene(std::make_unique<ResultsScene>(app_, summary_, creditsEarned_), 0.8f);
}

void EndingScene::Update(float dt) {
    time_ += dt;
    backdrop_.Update(dt);
    const Input& in = app_.In();
    const bool skip =
        in.Pressed(Action::Confirm) || in.Pressed(Action::Back) || in.Pressed(Action::Pause) || in.MouseClicked();
    if (time_ > kSkipDelay && skip) {
        app_.Audio().Play(SfxId::UiConfirm, 0.7f);
        Finish();
    }
}

void EndingScene::DrawWorld() { backdrop_.Draw(app_); }

void EndingScene::ConfigurePostFx(PostFxParams& params) const {
    params.vignette = 0.85f;
    params.exposure = 1.1f;
}

void EndingScene::DrawUi() {
    const Vector2 ui = app_.Gfx().UiSize();
    // Darken the backdrop so text stays the focus.
    DrawRectangleRec({0.0f, 0.0f, ui.x, ui.y}, Color{2, 4, 12, 150});
    if (time_ < kCreditsStart) {
        DrawEpilogue();
    } else {
        DrawCredits();
    }
    ui::Prompt(app_, {ui.x - 50.0f, ui.y - 50.0f}, "ENTER", "A", "CONTINUE", Align::Right, 20.0f);
}

void EndingScene::DrawEpilogue() {
    const Vector2 ui = app_.Gfx().UiSize();
    TextRenderer& text = app_.Gfx().Text();
    const float fadeOut = Saturate((kCreditsStart - time_) / 1.0f);
    const float top = ui.y * 0.5f - 170.0f;
    for (std::size_t i = 0; i < kEpilogue.size(); ++i) {
        const float start = kFirstLine + static_cast<float>(i) * kLineInterval;
        if (time_ < start) {
            break;
        }
        const EpilogueLine& line = kEpilogue[i];
        const std::string full = line.text;
        const auto shown = std::min(full.size(), static_cast<std::size_t>((time_ - start) * kTypeSpeed));
        const float alpha = Saturate((time_ - start) / 0.4f) * fadeOut;
        const float y = top + static_cast<float>(i) * 70.0f;
        const std::string visible = full.substr(0, shown);
        if (line.heading) {
            const Color glow = i == 0 ? palette::kUiAccent : palette::kUiGood;
            text.DrawGlow(FontId::Heading, visible, {ui.x * 0.5f, y}, 40.0f, WithAlpha(WHITE, alpha),
                          WithAlpha(glow, alpha), Align::Center, 0.15f);
        } else {
            text.Draw(FontId::Body, visible, {ui.x * 0.5f, y + 6.0f}, 32.0f, WithAlpha(palette::kUiText, alpha),
                      Align::Center);
        }
    }
}

void EndingScene::DrawCredits() {
    const Vector2 ui = app_.Gfx().UiSize();
    TextRenderer& text = app_.Gfx().Text();
    const std::vector<CreditLine> credits = BuildCredits(summary_);

    // The roll stops once the final line reaches the middle of the screen.
    float lastOffset = 0.0f;
    for (std::size_t i = 0; i + 1 < credits.size(); ++i) {
        lastOffset += LineHeight(credits[i].kind);
    }
    const float maxScroll = ui.y + 40.0f + lastOffset - ui.y * 0.45f;
    const float elapsed = time_ - kCreditsStart;
    const float scroll = std::min(elapsed * kScrollSpeed, maxScroll);
    if (elapsed * kScrollSpeed > maxScroll + kAutoContinue * kScrollSpeed) {
        Finish();
    }

    float y = ui.y + 40.0f - scroll;
    for (const CreditLine& line : credits) {
        // Fade lines in from the bottom edge and out at the top.
        const float alpha = Saturate((y - 40.0f) / 120.0f) * Saturate((ui.y - y) / 120.0f);
        if (alpha > 0.0f) {
            const Vector2 at{ui.x * 0.5f, y};
            switch (line.kind) {
            case CreditKind::Title:
                text.DrawGlow(FontId::Display, line.text, at, 64.0f, WithAlpha(WHITE, alpha),
                              WithAlpha(palette::kUiAccent, alpha), Align::Center, 0.08f);
                break;
            case CreditKind::Heading:
                text.Draw(FontId::Heading, line.text, at, 22.0f, WithAlpha(palette::kUiGood, alpha), Align::Center,
                          0.3f);
                break;
            case CreditKind::Body:
                text.Draw(FontId::Body, line.text, at, 30.0f, WithAlpha(palette::kUiText, alpha), Align::Center);
                break;
            case CreditKind::Gap: break;
            }
        }
        y += LineHeight(line.kind);
    }
}

